"""Regenerate vectors/vectors.json and rust/tests/vectors.rs from python/tests/vectors.py.

python/tests/vectors.py is the source of truth (produced by the reference implementation and
cross-checked by python/tests/reference.py). Run this after changing it:

    python tools/sync_vectors.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "tests"))
import vectors  # noqa: E402


def as_json() -> dict:
    return {
        "permutationZeroState": vectors.PERMUTATION_ZERO_STATE,
        "aead": vectors.AEAD_VECTORS,
        "password": vectors.PASSWORD_VECTORS,
    }


def as_rust() -> str:
    rows = ",\n".join(
        '    ("%s", "%s", "%s", "%s", "%s")' % (v["key"], v["nonce"], v["aad"], v["pt"], v["out"])
        for v in vectors.AEAD_VECTORS
    )
    return f"""// Known-answer vectors shared with the Python and JavaScript implementations (see SPEC.md).
// Generated by tools/sync_vectors.py from python/tests/vectors.py; do not edit by hand.

pub const PERMUTATION_ZERO_STATE: &str = "{vectors.PERMUTATION_ZERO_STATE}";

/// (key, nonce, aad, plaintext, ciphertext || tag), all hex.
pub const AEAD_VECTORS: &[(&str, &str, &str, &str, &str)] = &[
{rows},
];
"""


def main() -> None:
    (ROOT / "vectors" / "vectors.json").write_text(
        json.dumps(as_json(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (ROOT / "rust" / "tests" / "vectors.rs").write_text(as_rust(), encoding="utf-8")
    print("vectors/vectors.json and rust/tests/vectors.rs regenerated")


if __name__ == "__main__":
    main()
