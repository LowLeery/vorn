"""Regenerate vectors/vectors.json and rust/tests/vectors.rs.

python/tests/vectors.py is the source of truth for the Vorn vectors (produced by the reference
implementation and cross-checked by python/tests/reference.py). The Rust file additionally holds
SHA-256, HMAC-SHA-256 and scrypt vectors computed with Python's standard library (hashlib, hmac),
so the dependency-free Rust implementations are checked against an independent one.

Run this after changing python/tests/vectors.py:

    python tools/sync_vectors.py
"""

import hashlib
import hmac
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "tests"))
import vectors  # noqa: E402

SHA_LENGTHS = (0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 121, 1000)
HMAC_CASES = (
    (b"", b""),
    (b"\x0b" * 20, b"Hi There"),
    (b"Jefe", b"what do ya want for nothing?"),
    (bytes(range(64)), bytes(range(200))),
    (bytes(range(65)), b"key longer than the block size"),
    (b"\xaa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First"),
)
SCRYPT_CASES = (
    (b"", b"", 4, 1, 1),
    (b"password", b"NaCl", 10, 8, 16),
    ("pässwörd-\U0001F511".encode(), bytes(range(16)), 10, 8, 1),
    (b"x" * 100, bytes(range(70)), 6, 2, 3),
    (b"pleaseletmein", b"SodiumChloride", 12, 8, 1),
)


def sha_message(n: int) -> bytes:
    return bytes(i % 256 for i in range(n))


def as_json() -> dict:
    return {
        "permutationZeroState": vectors.PERMUTATION_ZERO_STATE,
        "aead": vectors.AEAD_VECTORS,
        "password": vectors.PASSWORD_VECTORS,
    }


def as_rust() -> str:
    aead = ",\n".join(
        '    ("%s", "%s", "%s", "%s", "%s")' % (v["key"], v["nonce"], v["aad"], v["pt"], v["out"])
        for v in vectors.AEAD_VECTORS
    )
    sha = ",\n".join(
        '    (%d, "%s")' % (n, hashlib.sha256(sha_message(n)).hexdigest()) for n in SHA_LENGTHS
    )
    mac = ",\n".join(
        '    ("%s", "%s", "%s")' % (k.hex(), m.hex(), hmac.new(k, m, hashlib.sha256).hexdigest())
        for k, m in HMAC_CASES
    )
    scr = ",\n".join(
        '    ("%s", "%s", %d, %d, %d, "%s")'
        % (pw.hex(), salt.hex(), log_n, r, p,
           hashlib.scrypt(pw, salt=salt, n=1 << log_n, r=r, p=p, dklen=32, maxmem=1 << 28).hex())
        for pw, salt, log_n, r, p in SCRYPT_CASES
    )
    pwd = ",\n".join(
        '    ("%s", "%s", "%s", "%s")'
        % (v["password"].encode().hex(), v["aad"], v["plaintext"], v["blob"])
        for v in vectors.PASSWORD_VECTORS
    )
    return f"""// Known-answer vectors shared with the Python and JavaScript implementations (see SPEC.md).
// Generated by tools/sync_vectors.py; do not edit by hand.

#[rustfmt::skip]
#[allow(dead_code)]
pub const PERMUTATION_ZERO_STATE: &str = "{vectors.PERMUTATION_ZERO_STATE}";

/// (key, nonce, aad, plaintext, ciphertext || tag), all hex.
#[rustfmt::skip]
#[allow(dead_code)]
pub const AEAD_VECTORS: &[(&str, &str, &str, &str, &str)] = &[
{aead},
];

/// (message length, SHA-256 hex). The message is the bytes `i % 256` for `i` in `0..length`.
/// Computed with Python's hashlib.
#[rustfmt::skip]
#[allow(dead_code)]
pub const SHA256_VECTORS: &[(usize, &str)] = &[
{sha},
];

/// (key, message, HMAC-SHA-256), all hex. Computed with Python's hmac module.
#[rustfmt::skip]
#[allow(dead_code)]
pub const HMAC_VECTORS: &[(&str, &str, &str)] = &[
{mac},
];

/// (password, salt, log2(n), r, p, 32-byte derived key), bytes as hex. Computed with hashlib.scrypt.
#[rustfmt::skip]
#[allow(dead_code)]
pub const SCRYPT_VECTORS: &[(&str, &str, u8, u32, u32, &str)] = &[
{scr},
];

/// (password UTF-8, aad, plaintext, container), all hex; password container of SPEC section 4.
#[rustfmt::skip]
#[allow(dead_code)]
pub const PASSWORD_VECTORS: &[(&str, &str, &str, &str)] = &[
{pwd},
];
"""


def main() -> None:
    (ROOT / "vectors" / "vectors.json").write_text(
        json.dumps(as_json(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (ROOT / "rust" / "tests" / "vectors.rs").write_text(as_rust(), encoding="utf-8")
    print("vectors/vectors.json and rust/tests/vectors.rs regenerated")


if __name__ == "__main__":
    main()
